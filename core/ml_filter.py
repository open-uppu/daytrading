"""
Machine Learning & Quantitative Confidence Filter (ML Meta-Labeling).
Based on Marcos López de Prado's Advances in Financial Machine Learning.

Extracts microstructure and technical features from live/historical price windows
and predicts the probability P(Trade Success >= TP before SL).
"""

from typing import Dict, Any, List, Optional, Tuple
import os
import logging
import numpy as np
import pandas as pd
from sklearn.ensemble import HistGradientBoostingClassifier, RandomForestClassifier

from core.indicators import compute_all_indicators, compute_ema

logger = logging.getLogger("ml_filter")


class MLQuantFilter:
    """
    ML Meta-Labeling and Quantitative Statistical Confidence Filter.
    Evaluates candidate trade proposals generated by primary strategies
    and gates them based on statistical machine-learned win probability.
    """

    FEATURE_COLS = [
        'feat_trend_alignment',
        'feat_fast_ema_spread',
        'feat_ema20_50_spread',
        'feat_rsi',
        'feat_rsi_velocity',
        'feat_vol_regime',
        'feat_body_ratio',
        'feat_upper_wick',
        'feat_lower_wick',
        'feat_session_hour',
        'action_code'
    ]

    def __init__(self, confidence_threshold: float = 0.70):
        self.confidence_threshold = confidence_threshold
        self.models: Dict[str, Any] = {}
        self.is_trained: Dict[str, bool] = {
            "xauusd": False,
            "btcusd": False,
            "ethusd": False
        }

    @staticmethod
    def extract_features(df_window: pd.DataFrame, action: str) -> Optional[np.ndarray]:
        """
        Extracts 11-dimensional quant feature vector from a bar window.
        """
        if len(df_window) < 35:
            return None

        df = df_window.copy()
        if 'ema_9' not in df.columns:
            df['ema_9'] = compute_ema(df['close'], 9)
        if 'ema_21' not in df.columns:
            df['ema_21'] = compute_ema(df['close'], 21)
        if 'ema_50' not in df.columns:
            df['ema_50'] = compute_ema(df['close'], 50)
        if 'ema_200' not in df.columns:
            df['ema_200'] = compute_ema(df['close'], 200)

        df = compute_all_indicators(df)
        latest = df.iloc[-1]
        prev = df.iloc[-2] if len(df) >= 2 else latest

        c_close = float(latest['close'])
        c_open = float(latest['open'])
        c_high = float(latest['high'])
        c_low = float(latest['low'])
        c_atr = max(float(latest.get('atr_14', 1.0)), 0.05)

        ema_9 = float(latest['ema_9'])
        ema_21 = float(latest['ema_21'])
        ema_20 = float(latest.get('ema_20', ema_21))
        ema_50 = float(latest.get('ema_50', c_close))
        ema_200 = float(latest.get('ema_200', c_close))

        rsi = float(latest.get('rsi_14', 50.0))
        prev_rsi = float(prev.get('rsi_14', rsi))
        rsi_vel = rsi - prev_rsi

        rolling_atr = df['atr_14'].rolling(20).mean().iloc[-1] if len(df) >= 20 else c_atr
        vol_regime = c_atr / (rolling_atr + 1e-5)

        candle_range = max(c_high - c_low, 1e-5)
        body = abs(c_close - c_open)
        body_ratio = body / candle_range
        upper_wick = (c_high - max(c_close, c_open)) / candle_range
        lower_wick = (min(c_close, c_open) - c_low) / candle_range

        hour = 12
        if 'timestamp' in df.columns:
            try:
                hour = pd.to_datetime(latest['timestamp']).hour
            except Exception:
                hour = 12

        action_code = 1.0 if action.upper() == "BUY" else 0.0

        vector = [
            (c_close - ema_200) / c_atr,      # feat_trend_alignment
            (ema_9 - ema_21) / c_atr,          # feat_fast_ema_spread
            (ema_20 - ema_50) / c_atr,         # feat_ema20_50_spread
            rsi,                               # feat_rsi
            rsi_vel,                           # feat_rsi_velocity
            vol_regime,                        # feat_vol_regime
            body_ratio,                        # feat_body_ratio
            upper_wick,                        # feat_upper_wick
            lower_wick,                        # feat_lower_wick
            float(hour),                       # feat_session_hour
            action_code                        # action_code
        ]
        return np.array(vector).reshape(1, -1)

    def train_model(
        self,
        df_history: pd.DataFrame,
        asset_symbol: str,
        tp_mult: float = 1.0,
        sl_mult: float = 1.4,
        trail_be_r: float = 0.70
    ) -> bool:
        """
        Trains an out-of-sample Meta-Labeling classifier on historical bars.
        """
        sym = asset_symbol.lower()
        n = len(df_history)
        if n < 200:
            logger.warning("Insufficient historical bars to train ML Meta-Labeler.")
            return False

        df = df_history.copy()
        df['ema_9'] = compute_ema(df['close'], 9)
        df['ema_21'] = compute_ema(df['close'], 21)
        df['ema_50'] = compute_ema(df['close'], 50)
        df['ema_200'] = compute_ema(df['close'], 200)
        df = compute_all_indicators(df)

        atr = df['atr_14'].replace(0, 0.01)
        df['feat_trend_alignment'] = (df['close'] - df['ema_200']) / atr
        df['feat_fast_ema_spread'] = (df['ema_9'] - df['ema_21']) / atr
        df['feat_ema20_50_spread'] = (df['ema_20'] - df['ema_50']) / atr
        df['feat_rsi'] = df['rsi_14']
        df['feat_rsi_velocity'] = df['rsi_14'].diff(2).fillna(0)
        rolling_atr = df['atr_14'].rolling(20).mean()
        df['feat_vol_regime'] = df['atr_14'] / (rolling_atr + 1e-5)

        rng = df['high'] - df['low'] + 1e-5
        body = (df['close'] - df['open']).abs()
        df['feat_body_ratio'] = body / rng
        df['feat_upper_wick'] = (df['high'] - df[['open', 'close']].max(axis=1)) / rng
        df['feat_lower_wick'] = (df[['open', 'close']].min(axis=1) - df['low']) / rng

        if 'timestamp' in df.columns:
            ts = pd.to_datetime(df['timestamp'])
            df['feat_session_hour'] = ts.dt.hour
        else:
            df['feat_session_hour'] = 12

        # Extract candidate samples
        samples = []
        for i in range(40, n - 35):
            row = df.iloc[i]
            prev = df.iloc[i - 1]
            close_p = row['close']
            c_atr = max(row['atr_14'], 0.1)

            action = None
            # Cross or Pullback Setup
            if (prev['ema_9'] <= prev['ema_21']) and (row['ema_9'] > row['ema_21']) and close_p > row['ema_200']:
                action = "BUY"
            elif (prev['ema_9'] >= prev['ema_21']) and (row['ema_9'] < row['ema_21']) and close_p < row['ema_200']:
                action = "SELL"

            if action:
                # Triple Barrier Simulation
                target_tp = close_p + (tp_mult * c_atr) if action == "BUY" else close_p - (tp_mult * c_atr)
                init_sl = close_p - (sl_mult * c_atr) if action == "BUY" else close_p + (sl_mult * c_atr)
                trigger_be = close_p + (trail_be_r * c_atr) if action == "BUY" else close_p - (trail_be_r * c_atr)

                curr_sl = init_sl
                is_win = 0
                for j in range(i + 1, min(i + 35, n)):
                    fh = df.iloc[j]['high']
                    fl = df.iloc[j]['low']
                    if action == "BUY":
                        if fh >= trigger_be:
                            curr_sl = close_p + (0.05 * c_atr)
                        if fh >= target_tp or (curr_sl > close_p and fl <= curr_sl):
                            is_win = 1
                            break
                        elif fl <= curr_sl:
                            is_win = 0
                            break
                    else:
                        if fl <= trigger_be:
                            curr_sl = close_p - (0.05 * c_atr)
                        if fl <= target_tp or (curr_sl < close_p and fh >= curr_sl):
                            is_win = 1
                            break
                        elif fh >= curr_sl:
                            is_win = 0
                            break

                f_vals = row[[c for c in self.FEATURE_COLS if c != 'action_code']].to_dict()
                f_vals['action_code'] = 1.0 if action == "BUY" else 0.0
                f_vals['target_win'] = is_win
                samples.append(f_vals)

        sample_df = pd.DataFrame(samples)
        if len(sample_df) < 30:
            return False

        X = sample_df[self.FEATURE_COLS]
        y = sample_df['target_win']

        clf = HistGradientBoostingClassifier(max_iter=80, min_samples_leaf=6, random_state=42)
        clf.fit(X, y)

        self.models[sym] = clf
        self.is_trained[sym] = True
        logger.info(f"Trained ML Quant Filter for {sym.upper()} on {len(sample_df)} historical setups.")
        return True

    def predict_confidence(
        self,
        df_window: pd.DataFrame,
        action: str,
        asset_symbol: str = "xauusd"
    ) -> float:
        """
        Predicts confidence probability P(Win).
        If model not yet trained, returns heuristic multi-factor score.
        """
        sym = asset_symbol.lower()
        vector = self.extract_features(df_window, action)
        if vector is None:
            return 0.50

        if sym in self.models and self.is_trained.get(sym, False):
            clf = self.models[sym]
            try:
                probs = clf.predict_proba(vector)[0]
                return float(probs[1]) if len(probs) > 1 else 0.50
            except Exception:
                pass

        # Fallback Quantitative Multi-Factor Confidence Score
        # Combines Trend alignment, RSI momentum, and Wick Rejection
        df = df_window
        latest = df.iloc[-1]
        c_close = float(latest['close'])
        c_open = float(latest['open'])
        c_high = float(latest['high'])
        c_low = float(latest['low'])
        rsi = float(latest.get('rsi_14', 50.0))
        ema_200 = float(latest.get('ema_200', c_close))

        rng = max(c_high - c_low, 1e-5)
        score = 0.50

        if action.upper() == "BUY":
            if c_close > ema_200:
                score += 0.15
            if 45.0 <= rsi <= 65.0:
                score += 0.12
            lower_wick = (min(c_close, c_open) - c_low) / rng
            if lower_wick >= 0.35:
                score += 0.10
        elif action.upper() == "SELL":
            if c_close < ema_200:
                score += 0.15
            if 35.0 <= rsi <= 55.0:
                score += 0.12
            upper_wick = (c_high - max(c_close, c_open)) / rng
            if upper_wick >= 0.35:
                score += 0.10

        return min(max(score, 0.10), 0.95)

    def evaluate_proposal(
        self,
        signal: Dict[str, Any],
        df_window: pd.DataFrame,
        asset_symbol: str = "xauusd",
        custom_threshold: Optional[float] = None
    ) -> Tuple[bool, float, Dict[str, Any]]:
        """
        Gates a trade proposal.
        Returns: (passed: bool, confidence: float, details: dict)
        """
        action = signal.get("action", "HOLD")
        if action not in ["BUY", "SELL"]:
            return True, 0.50, {"reason": "HOLD action ignored by ML filter"}

        th = custom_threshold if custom_threshold is not None else self.confidence_threshold
        conf = self.predict_confidence(df_window, action, asset_symbol)

        passed = conf >= th
        details = {
            "action": action,
            "ml_confidence": round(conf, 3),
            "threshold": th,
            "passed": passed,
            "reason": f"ML Confidence {conf:.1%} vs Threshold {th:.1%}"
        }
        return passed, conf, details
